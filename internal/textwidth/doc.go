// Package textwidth は、文字列を書記素クラスタに分け、表示する形と表示幅を決める（docs/SPEC-tui.md §4）。
// 書記素クラスタの区切りと表示幅は、このパッケージだけが決める（tui T4）。
//
// 表は Unicode 18.0.0 のデータ（ucd/）から go generate で作る（tables.go）。x/text/width は使わない。
//
// # API
//
//	c, rest := textwidth.Next(s)      // 先頭の書記素クラスタと残り
//	for c := range textwidth.All(s)   // 書記素クラスタを順に
//	w := textwidth.Width(s)           // 表示幅の和
//
// Cluster は、元のバイト列（Text）、分類（Class）、表示する形（Display）、その表示幅（Width、1 以上）、
// 幅が端末によって違いうるかの印（Varies）を持つ。表示する形を使うのは表示だけで、元のバイト列は変えない（filer U4）。
//
//	分類          表示する形
//	Normal        そのまま
//	Forbidden     ?（制御文字、双方向の制御文字と方向の印、行区切り・段落区切り）
//	InvalidByte   ?（不正な UTF-8 のバイト。1 バイトずつ）
//	Invisible     ?（既定で無視される文字だけのもの、結合文字で始まるもの、幅が 0 になるもの）
//	Unstable      簡略な形（ZWJ の並び → 最初の絵文字、肌の色・VS16 → 除く、キーキャップ・タグ → 最初の文字、地域指示記号 → ?）
//
// 幅の規則: 書記素クラスタの幅は、表示する形の各符号位置の幅の和。East Asian Width が W・F なら 2、
// 結合文字（Mn・Me）・異体字セレクタ・既定で無視される文字・ハングルの中声と終声の字母は 0、それ以外は 1（幅が曖昧な文字を含む）。
// 端末で実測した結果（docs/probe-results）をテストの期待値にしている。
//
// Varies が付くのは、幅が曖昧な文字（East Asian Width が A）、Unicode 16.0 より新しい絵文字、幅が 3 以上の書記素クラスタ。
// screen は、その後で位置を指定し直す（tui §6）。
//
// # 担う不変条件
//
// T2（表示する文字列から制御シーケンスを出力しない）: 表示する形は、端末に出してはいけない文字と不正なバイトを含まない。
// screen はこの形を出力する。
//
// T4（幅の判断を 1 か所にする）: screen・lineedit・textfmt は、書記素クラスタの区切りと幅をこのパッケージで得る。
//
// T6（画面は格子と一致する）の支え: 端末によって幅や描き方が割れる書記素クラスタ（不安定な書記素クラスタ・見えない書記素クラスタ）を
// 表示する形に置き換え、残りの違いうるものに Varies の印を付ける。
//
// # 表を作り直す
//
// ucd/ のファイルを新しい版に置き換えて、このフォルダで go generate を実行する。ucd/ のファイルの版がそろっていなければ失敗する。
