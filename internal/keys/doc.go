// Package keys は、端末からの入力（バイト列）をイベントに変える純粋な状態機械（docs/SPEC-tui.md §5）。
//
// Unix は端末から読んだバイト列を、Windows は VT の入力モードで読んだ入力のレコードを term がバイト列に変えたものを渡す。
// keys は時刻を読まず、goroutine も使わない。時刻は呼び出し側が渡すので、待ち時間をテストで操作できる。
//
// # API
//
//	var d keys.Decoder                     // ゼロ値で使える
//	ev := d.Feed(b, now)                   // 時刻 now に届いた入力を加え、確定したイベントを返す
//	ev = d.Tick(now)                       // 待ち時間が過ぎた保留中の入力を確定する
//	deadline, ok := d.Deadline()           // 次に Tick を呼ぶべき時刻（保留中の入力がなければ ok は false）
//	d.SetCursorPositionExpected(true)      // カーソル位置の問い合わせの応答を待っている間
//
// Event の種類は、キー（Key・Mod・Rune）、貼り付け（Text）、カーソル位置の報告（Row・Col）、解釈できない入力。
// どのイベントも、元の入力（Raw）を持つ。
//
// # 解釈
//
//   - 文字は KeyRune のキー。制御文字は Ctrl 付きの文字（0x01 は Ctrl＋a、0x08 は Ctrl＋h、0x00 は Ctrl＋空白）。
//     ただし 0x09 は Tab、0x0D は Enter、0x1B は Esc、0x7F は Backspace（区別できないものは、こちらにする）。
//   - ESC の後に続きが待ち時間（50 ミリ秒）の間に届かなければ Esc。届けば Alt 付きのキーか、シーケンス。
//     待ち時間は、保留中の入力が最後に届いた時刻から数える。
//     Alt は 1 段だけ: ESC ESC ESC は Esc と Alt＋Esc（押し続けた Esc を 1 つのイベントにまとめない）。
//     ESC [ の直後に CSI にならないバイトが来たら Alt＋[ にする。
//   - CSI（ESC [）と SS3（ESC O）のシーケンスは、フェーズ12で記録した 4 端末のもの（xterm の形）を解釈する。
//     修飾キーは ESC[1;<修飾キー>A・ESC[3;<修飾キー>~ の形。それ以外は解釈できない入力にする。
//     終わりのバイトが 64 バイトまでに届かない CSI は、解釈できない入力にする（保留が増え続けないように）。
//   - ESC[行;桁R は、SetCursorPositionExpected(true) の間だけカーソル位置の報告。それ以外では Shift などの付いた F3。
//   - bracketed paste（ESC[200~ から ESC[201~ まで）は貼り付けのイベント。中身をキーとして解釈しない（filer U2）。
//     終わりの印が届かないときは、最後の入力から 1 秒で区切って貼り付けのイベントにし、終わりの印までは貼り付けを続ける。
//     その後さらに 1 秒なにも届かなければ、貼り付けを終える。
//   - 不正な UTF-8 のバイトは、1 バイトずつ解釈できない入力にする。
//
// # 担う不変条件
//
// T3（入力を失わず、作らない）: 受け取ったバイトは、すべていずれかのイベントの Raw に入る。
// イベントの Raw を順につなぐと、受け取った入力と一致する。存在しない入力からイベントを作らない。
// 待ち時間より後の時刻で Tick を 1 回呼べば、保留中の入力はなくなる。
// 同じバイト列を、待ち時間より短い間隔で任意の位置で分けて渡しても、同じイベントの列になる。
