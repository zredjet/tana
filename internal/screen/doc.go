// Package screen は、セルの格子に描き、前回の出力からの差分を端末に書く（docs/SPEC-tui.md §6）。
//
// # API
//
//	s := screen.New(cols, rows)            // 空白で埋めた画面。最初の Flush で全体を書く
//	s.Put(r, x, y, text, st) int           // 領域 r の (x, y) から text を置き、使った桁数を返す
//	s.Fill(r, st)                          // 領域 r を空白で塗る
//	s.SetCursor(x, y, visible)             // 本物のカーソルの位置と表示・非表示
//	s.Flush(w) error                       // 前回の出力からの差分を w に書く。書き込みに失敗したら、次は全体を書く
//	s.Resize(cols, rows) / s.Invalidate()  // 次の Flush で全体を書く
//	s.Size() / s.Cell(x, y) / s.Row(y)     // 格子を読む（テスト用）
//	s.NoColor                              // 色を出力しない（属性は残す）
//
// Style は前景・背景の色（16 色と既定の色）と属性（太字・暗く・下線・反転）。Region は画面の矩形で、画面からはみ出してもよい。
// Cell は格子の 1 つのセル。幅 N の書記素クラスタは、先頭のセルと N−1 個の続きのセル（Width が 0）。
//
// # 使い方
//
//	s := screen.New(cols, rows)
//	s.NoColor = os.Getenv("NO_COLOR") != ""
//	pane := screen.Region{X: 0, Y: 1, W: 40, H: 22}
//	s.Fill(pane, screen.Style{})
//	s.Put(pane, 0, 0, name, screen.Style{FG: screen.ColorBlue}) // 欄ごとに Put する（位置を指定し直す場所になる）
//	s.SetCursor(x, y, true)                                      // 入力欄の本物のカーソル（IME の変換中の文字はここに出る）
//	err := s.Flush(w)                                             // 差分を書く
//	s.Resize(cols, rows) / s.Invalidate()                         // 大きさが変わった・端末の内容が分からなくなったとき
//
// 書記素クラスタの区切りと幅、表示する形（? や絵文字の簡略な形）は、すべて textwidth で得る（T4）。
// 自動改行（DECAWM）は term が切っておく。screen は行をまたいで書かない。
//
// # 担う不変条件
//
// T2（表示する文字列から制御シーケンスを出力しない）: 書記素クラスタは textwidth の表示する形で置くので、
// 格子に端末に出してはいけない文字は入らない。出力する制御シーケンスは、カーソルの位置（ESC[行;桁H）、
// SGR（ESC[…m）、カーソルの表示・非表示（ESC[?25h・ESC[?25l）、同期出力（ESC[?2026h・ESC[?2026l）だけ。
//
// T5（領域の外に描かない）: Put と Fill は領域の中だけを変える。幅 2 以上の書記素クラスタが領域の端にかかるときは、
// 領域の中の部分を空白で埋める。例外は、前に描いた幅 2 以上の書記素クラスタが領域の端にまたがっている場合で、
// 領域の外に残る部分を空白にする（端末もそうするので、格子を合わせる）。
//
// T6（画面は格子と一致する）: Flush の後、端末の表示は格子と一致する（端末の幅の計算が textwidth と同じ場合）。
// 合わない端末でも、ずれが広がらないように、行の始め・欄の始め・幅が違いうる書記素クラスタの後・左のセルと結合しうる書記素クラスタの前と後ろで
// 位置を指定し直す。幅が違いうる書記素クラスタは、幅 2 以上なら先に空白で消してから書き、後ろの 1 つを書き直す。
// 左のセルと結合しうる書記素クラスタも、先に空白で消してから書く。位置を指定し直しても左のセルにまとめる端末
// （Windows Terminal・iTerm2。tui §9 の VT7）では、ずれがその書記素クラスタのセルと左のセルの中で止まる。
// 1 回の出力は、同期出力（mode 2026）で囲む。
