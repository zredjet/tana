// Package app は、ファイラーの画面の状態と操作の流れを持つ（filer §4・§10）。
//
// 端末の入出力に依存しない。tui がキー入力を Action に変えて Do に渡し、状態を読んで描く。
// 時間のかかる処理（列挙、リンク先の読み取り、関連付けで開く、計画、実行）は Cmd として返し、tui が作業用の goroutine で動かして、
// 戻り値を Update に渡す（filer U5）。状態を変えるのは Do と Update だけで、どちらもイベントループの goroutine から呼ぶ。
//
// 画面の構成に依存させないため、ペインは「フォルダの表示」の並びとして持つ（filer §4）。左右などの配置は tui が決める。
//
// # UI の骨格（filer §4）
//
// 画面の状態は部品（component）の木で持つ。土台は作業場（workspace.go）で、その上に重ねる部品（ダイアログ、ファイル操作の画面）を積む。
//   - フォーカスの道筋（FocusPath）: 重ねる部品があれば一番上のもの、なければ [操作中のペイン, 作業場]。
//     Do は、Action.Role の部品か、道筋の内側から見て操作表にその操作を持つ最初の部品に届ける。
//   - 門（component.go）: 操作表の各行は、描く前でも行う（GateFree）か、部品が道筋の一番内側になってから画面を描いた後だけ行う（GateAfterDraw）かを
//     必ず宣言する。先行入力の守り（U2）はここだけで行い、画面ごとに描いた回数を比べない。
//   - 持ち主と ID: ファイル操作の流れ（flow.go）とペインは ID で引く。作業用の goroutine の結果は ID で届け先を決め、持ち主がいなければ捨てる。
//     進捗と中止の確認の部品は、流れの型ではなく runner（止められる実行）だけを見る。
//
// tui が読むもの: 作業場のアクセサ（Panes・Active・Message・Preview など）、FocusPath（キーの表を引く順）、
// Modals（重ねた部品の内容。View の型で描き方を選ぶ）。キーは tui の keymap が Action に変え、Action.Role の部品に届く。
